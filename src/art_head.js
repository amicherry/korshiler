const OUT = '#1b1a21';
function shade(hex, amt) {
  const n = parseInt(hex.slice(1), 16), c = v => Math.max(0, Math.min(255, v));
  return '#' + ((1 << 24) | (c((n >> 16) + amt) << 16) | (c((n >> 8 & 255) + amt) << 8) | c((n & 255) + amt)).toString(16).slice(1);
}

